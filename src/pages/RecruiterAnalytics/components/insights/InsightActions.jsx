import React, { createContext, useContext, useMemo, useState } from "react";
import { useLocation, useNavigate } from "react-router-dom";
import { FiX } from "react-icons/fi";
import { AuthContext } from "../../../../context/AuthContext";
import AnalyzeWithAI from "../../../FinancialReports/AnalyzeWithAI";
import EvidenceDrawer from "../drawers/EvidenceDrawer";
import { useCommentary } from "../../hooks/useCommentary";
import { useSalesAccess } from "../../access/SalesAccessContext";
import { INSIGHT_CATEGORIES } from "../../insights/phrasing";
import { SALES_ANALYTICS_BASE } from "../../config/tabs";
import { byUnit } from "../../utils/format";

const InsightActionsContext = createContext(null);

const AI_TYPES = { money: "money", pct: "pct" };

/** Evidence rows as the AI drawer's supporting table; non-money values are pre-formatted. */
function supportingTable(evidence) {
  if (!evidence?.rows?.length) return [];
  const columns = evidence.columns.map((c) => ({ key: c.key, label: c.label, type: AI_TYPES[c.unit] || "text" }));
  const rows = evidence.rows.map((r) => {
    const out = {};
    for (const c of evidence.columns) {
      const v = r[c.key];
      out[c.key] = AI_TYPES[c.unit] || c.unit === "text" || c.unit === "date" ? v : v == null ? "" : byUnit(v, c.unit);
    }
    return out;
  });
  return [{ title: evidence.title, columns, rows }];
}

/** The insight and its evidence as plain text for the AI service. Restricted values arrive empty. */
function insightContext(insight, { pageLabel, sectionTitle, meta }) {
  const lines = [
    "Staffing Recruiter Analytics insight, generated by rules over the viewer's authorized sample data.",
    `Page: ${pageLabel}${sectionTitle ? ` · Section: ${sectionTitle}` : ""}`,
  ];
  if (meta) {
    lines.push(`Period: ${meta.period.label} · Compared with: ${meta.compareBasis} · Scope: ${meta.scope.label} · Currency: USD · Data as of ${meta.asOf}`);
  }
  lines.push(`Insight: ${insight.title}`, `What it means: ${insight.meaning}`);
  if (insight.actions?.length) lines.push("Suggested actions:", ...insight.actions.map((a) => `- ${a}`));
  const ev = insight.evidence;
  if (ev?.rows?.length) {
    lines.push(`Evidence — ${ev.title}:`, ev.columns.map((c) => c.label).join(" | "));
    for (const r of ev.rows.slice(0, 40)) {
      lines.push(ev.columns.map((c) => (r[c.key] == null ? "Restricted/none" : c.unit === "text" || c.unit === "date" ? r[c.key] : byUnit(r[c.key], c.unit))).join(" | "));
    }
  }
  lines.push("Separate observed facts from estimated risk and hypothetical improvements.");
  return lines.join("\n");
}

function SaveCommentaryModal({ item, onCancel, onSave }) {
  const [title, setTitle] = useState(item.title);
  const [text, setText] = useState(`${item.meaning}\n\n${(item.actions || []).map((a) => `• ${a}`).join("\n")}`);
  return (
    <div className="fixed inset-0 z-[60] bg-black/40 flex items-center justify-center p-4" role="dialog" aria-modal="true" aria-label="Save commentary">
      <div className="bg-white rounded-xl shadow-xl w-full max-w-lg p-5 space-y-3">
        <div className="flex items-center justify-between">
          <h3 className="font-semibold text-sky-900">Save performance commentary</h3>
          <button type="button" onClick={onCancel} aria-label="Close" className="text-sky-600 hover:text-sky-900">
            <FiX />
          </button>
        </div>
        <label className="block text-xs font-medium text-sky-700">
          Title
          <input value={title} onChange={(e) => setTitle(e.target.value)} className="mt-1 w-full border border-sky-200 rounded-md px-2 py-1.5 text-sm text-sky-900" />
        </label>
        <label className="block text-xs font-medium text-sky-700">
          Commentary
          <textarea value={text} onChange={(e) => setText(e.target.value)} rows={7} className="mt-1 w-full border border-sky-200 rounded-md px-2 py-1.5 text-sm text-sky-900" />
        </label>
        <div className="flex justify-end gap-2">
          <button type="button" onClick={onCancel} className="px-3 py-1.5 rounded-lg border border-sky-200 text-sm text-sky-800 hover:bg-sky-50">
            Cancel
          </button>
          <button
            type="button"
            disabled={!text.trim()}
            onClick={() => onSave({ title: title.trim() || item.title, text: text.trim() })}
            className="px-3 py-1.5 rounded-lg bg-sky-900 text-white text-sm font-semibold hover:bg-sky-800 disabled:opacity-50"
          >
            Save
          </button>
        </div>
      </div>
    </div>
  );
}

/**
 * One host per page for what an insight can do: show its evidence, refine it
 * with the AI service, open What-If with its lever, and save it as commentary.
 * Section insight lists read these handlers from context.
 */
export function InsightActionsProvider({ pageKey, pageLabel, meta, sections = [], repId, children }) {
  const { access, can } = useSalesAccess();
  const auth = useContext(AuthContext) || {};
  const navigate = useNavigate();
  const location = useLocation();
  const commentary = useCommentary(pageKey, {
    savedBy: access?.user?.name || "",
    filtersLabel: meta ? `${meta.period.label} vs ${meta.compareBasis} · ${meta.scope.label}` : "",
  });
  const [evidence, setEvidence] = useState(null);
  const [refining, setRefining] = useState(null);
  const [saving, setSaving] = useState(null);
  const sectionTitle = (id) => sections.find((s) => s.id === id)?.title;
  const canWhatIf = can("create_scenario");

  const value = useMemo(
    () => ({
      commentary,
      analyze: (i) => setEvidence({ title: i.title, subtitle: i.meaning, sections: i.evidence ? [i.evidence] : [] }),
      refine: (i) => setRefining(i),
      save: (i) => setSaving(i),
      whatIf: canWhatIf
        ? (i) =>
            navigate(
              { pathname: `${SALES_ANALYTICS_BASE}/what-if`, search: location.search },
              { state: { prefill: i.whatIf?.prefill || {}, fromInsight: i.title, repId: i.whatIf?.repId || repId } }
            )
        : null,
    }),
    [commentary, canWhatIf, navigate, location.search, repId]
  );

  const refineTarget = refining && { title: refining.title, component: "kpi", metric: INSIGHT_CATEGORIES[refining.category]?.label || null, period: meta?.period?.label || null };

  return (
    <InsightActionsContext.Provider value={value}>
      {children}
      <EvidenceDrawer open={!!evidence} onClose={() => setEvidence(null)} title={evidence?.title || ""} subtitle={evidence?.subtitle} sections={evidence?.sections} />
      <AnalyzeWithAI
        target={refineTarget}
        onClose={() => setRefining(null)}
        token={auth.token}
        reportId="recruiter_performance"
        reportLabel={`Staffing Recruiter Analytics · ${pageLabel}`}
        year={meta ? Number(meta.asOf.slice(0, 4)) : new Date().getFullYear()}
        currency="USD"
        filterLabels={meta ? [`Period: ${meta.period.label}`, `Compared with: ${meta.compareBasis}`, `Scope: ${meta.scope.label}`] : []}
        loadContext={async () => ({
          context: insightContext(refining, { pageLabel, sectionTitle: sectionTitle(refining.section), meta }),
          supporting: supportingTable(refining.evidence),
        })}
        onAddToReport={({ title, text }) =>
          commentary.save({
            insightId: refining.id,
            section: refining.section,
            title,
            text,
            category: INSIGHT_CATEGORIES[refining.category]?.label || refining.category,
            source: "ai",
          })
        }
      />
      {saving ? (
        <SaveCommentaryModal
          item={saving}
          onCancel={() => setSaving(null)}
          onSave={({ title, text }) => {
            commentary.save({
              insightId: saving.id,
              section: saving.section,
              title,
              text,
              category: INSIGHT_CATEGORIES[saving.category]?.label || saving.category,
            });
            setSaving(null);
          }}
        />
      ) : null}
    </InsightActionsContext.Provider>
  );
}

export function useInsightActions() {
  return useContext(InsightActionsContext);
}
